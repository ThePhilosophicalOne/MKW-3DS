#!/usr/bin/env python3
"""Unlock, expert-ghost and staff-roll tables from the user's original RMCU REL.

Writes include/mkw/unlock_tables.hpp (numbers only: bit indices, thresholds,
message ids, frame numbers, sound ids). Every table is read from
build/itembox-retail.rel (rel/StaticR.rel of the USA disc, hash-checked like
tools/verify_menu_retail.py) at the address the retail code reads it from.
USA addresses (analysis image at 0x8050BF60) with the PAL address the
unlocks plan used (findings/r1_unlocks_credits_plan.md):

  character unlock bits  USA 0x8088CDA8  PAL 0x80890F78  characterIsUnlocked 0x8054FED8
  vehicle unlock bits    USA 0x8088CE10  PAL 0x80890FE0  fn_1_3FD18 0x805500CC
  expert-ghost times     USA 0x8088CEA0  PAL 0x80891070  isFastStaffGhostUnlocked 0x80550468
  staff roll, part 1     USA 0x80892EF0  PAL 0x808939F8  credits page fn_1_BAE10 0x805CB1C4
  staff roll, part 2     USA 0x80892FA0  PAL 0x80893AA8  (same page)
  unlock-page voices     USA 0x808AD1B0  PAL 0x808B1EA0  fn_1_3589A0 0x80868D54
  character select order USA 0x808A3108  (CtrlMenuCharacterSelect, 3 weight classes x 8)

The output is deterministic, so the build step rewrites the committed header
with the same bytes.
"""
import argparse, hashlib, struct, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
from verify_menu_retail import BASE, EXPECTED_HASH

REL = ROOT/'build/itembox-retail.rel'
OUT = ROOT/'include/mkw/unlock_tables.hpp'


def read(rel, address, fmt):
    return struct.unpack_from('>'+fmt, rel, address-BASE)


def check(condition, what):
    if not condition: raise SystemExit('cook_unlock_tables: unexpected REL data: '+what)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--rel', type=Path, default=REL)
    parser.add_argument('--output', type=Path, default=OUT)
    args = parser.parse_args()
    if not args.rel.exists(): raise SystemExit('Missing '+str(args.rel)+' (the "game module" build step extracts it).')
    rel = args.rel.read_bytes()
    if hashlib.sha256(rel).hexdigest() != EXPECTED_HASH: raise SystemExit('Unsupported REL: needs the unmodified RMCU rel/StaticR.rel')

    character_bits = read(rel, 0x8088CDA8, '26i')
    vehicle_bits = read(rel, 0x8088CE10, '36i')
    expert = read(rel, 0x8088CEA0, '32I')
    roll1 = [read(rel, 0x80892EF0+16*i, '8H') for i in range(11)]
    roll2 = [read(rel, 0x80892FA0+16*i, '8H') for i in range(18)]
    voices = read(rel, 0x808AD1B0, '48I')
    order = read(rel, 0x808A3108, '24I')

    check(sum(b < 0 for b in character_bits) == 12 and sorted(b for b in character_bits if b >= 0) == list(range(14)), 'character bits')
    check(sum(b < 0 for b in vehicle_bits) == 18 and sorted(b for b in vehicle_bits if b >= 0) == list(range(34, 52)), 'vehicle bits')
    check(all(60000 <= t <= 200000 for t in expert), 'expert times')
    for roll in (roll1, roll2):
        last = 0
        for entry in roll:
            if entry[6] == 0 and entry[7] == 0: continue
            check(last <= entry[6] < entry[7], 'staff roll frames')
            last = entry[7]
    check(roll2[17] == (0,)*8, 'staff roll part 2 terminator')
    check(sorted(order) == list(range(24)), 'character select order')
    check(all(v == 914 for v in voices[24:]) and len(set(voices[:24])) == 24, 'unlock voices')

    def row(values, width=8):
        return ',\n '.join(','.join(str(v) for v in values[i:i+width]) for i in range(0, len(values), width))
    def roll(entries):
        return ',\n '.join('{{{%u,%u},{%u,%u},{%u,%u}},%u,%u}' % e for e in entries)
    text = f'''#pragma once
// Generated by tools/cook_unlock_tables.py from the original RMCU rel/StaticR.rel
// (build/itembox-retail.rel, sha256 {EXPECTED_HASH[:16]}...). Do not edit.
// Addresses: see the tool's docstring. Numbers only.
#include <array>
#include <cstdint>
namespace mkw::unlock_tables {{
// characterIsUnlocked (PAL 0x8054FED8): unlock bit of retail character ids 0..25, -1 = always unlocked.
// Mii ids (0x18..0x29) are handled in code (bits 12/13).
inline constexpr std::array<std::int8_t,26> CharacterBit{{{{
 {row(character_bits)}
}}}};
// fn_1_3FD18 (PAL 0x805500CC): unlock bit of retail vehicle ids 0..35, -1 = always unlocked.
inline constexpr std::array<std::int8_t,36> VehicleBit{{{{
 {row(vehicle_bits, 9)}
}}}};
// isFastStaffGhostUnlocked (PAL 0x80550468): the expert staff ghost of a course
// (retail course id) appears when the licence's best time is at most this (ms).
inline constexpr std::array<std::uint32_t,32> ExpertGhostMs{{{{
 {row(expert)}
}}}};
// fn_1_3589A0 (PAL 0x80868D54): sound id played by the unlock page's Next for a
// retail character id (0x392 skips; Miis use 914).
inline constexpr std::array<std::uint16_t,48> UnlockVoice{{{{
 {row(voices, 12)}
}}}};
// CtrlMenuCharacterSelect (USA 0x808A3108): retail character ids per weight
// class column (light, medium, heavy), button order.
inline constexpr std::array<std::array<std::uint8_t,8>,3> CharacterSelectOrder{{{{
 {{{{{row(order[0:8])}}}}},{{{{{row(order[8:16])}}}}},{{{{{row(order[16:24])}}}}}
}}}};
// Credits staff roll (fn_1_BB3A8 PAL 0x805CB75C): per entry the (title, name)
// message ids of the center, top and bottom slots, then the frames the entry
// comes in and goes out. Name 0 = slot hidden; title 0 = name-only template.
struct StaffRollEntry {{ std::uint16_t text[3][2]; std::uint16_t in, out; }};
inline constexpr StaffRollEntry StaffRollDemo[11]={{
 {roll(roll1)}
}};
inline constexpr StaffRollEntry StaffRollMovie[18]={{
 {roll(roll2)}
}};
}}
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    previous = args.output.read_text() if args.output.exists() else None
    if previous != text: args.output.write_text(text, newline='\n')
    print(f'unlock tables: {args.output} ({"unchanged" if previous == text else "written"})')


if __name__ == '__main__':
    main()
